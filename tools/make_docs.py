def make_wireframe(path):
    """Рисует эскиз главного окна (как в Figma, только кодом)."""
    w, h = 1100, 720
    img = Image.new("RGB", (w, h), "white")
    d = ImageDraw.Draw(img)
    font_path = "C:/Windows/Fonts/arial.ttf"
    f = ImageFont.truetype(font_path, 16)
    fb = ImageFont.truetype("C:/Windows/Fonts/arialbd.ttf", 16)
    fs = ImageFont.truetype(font_path, 13)
    gray, dark, line, accent = "#e9ecef", "#343a40", "#adb5bd", "#4c6ef5"

    def box(x, y, bw, bh, text="", fill=gray, font=f, color=dark, outline=line):
        d.rectangle([x, y, x + bw, y + bh], fill=fill, outline=outline, width=2)
        if text:
            tw = d.textlength(text, font=font)
            d.text((x + (bw - tw) / 2, y + (bh - font.size) / 2 - 1), text, fill=color, font=font)

    def note(x, y, text):
        d.text((x, y), text, fill="#c92a2a", font=fs)

    box(0, 0, w, 36, "Расшифровщик аудио", fill="#dee2e6", font=fb)
    d.text((14, 44), "Файл    Справка", fill=dark, font=f)
